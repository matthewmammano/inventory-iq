"""Verify the migrations fully describe the models.

`alembic check` only works against a database already at head, so this builds a
throwaway SQLite one, upgrades it, and compares the models to it. No real
database is read or written, so it is safe to run from a pre-commit hook.
"""

import os
import sys
import tempfile
from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

_REPO_ROOT = Path(__file__).resolve().parent.parent


def run() -> int:
    """Return 1 if any model change has no matching migration."""
    with tempfile.TemporaryDirectory() as scratch:
        # env.py reads settings.database_url, so the throwaway path has to be set before it imports.
        os.environ["DATABASE_URL"] = f"sqlite:///{Path(scratch) / 'migration_check.db'}"
        config = Config(str(_REPO_ROOT / "alembic.ini"))
        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:
            print(f"Models changed with no migration: {exc}")
            print("Generate one with: uv run alembic revision --autogenerate -m '<what changed>'")
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(run())
